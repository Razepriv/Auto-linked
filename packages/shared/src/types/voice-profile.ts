// ---------------------------------------------------------------------------
// Voice Profile domain types
// ---------------------------------------------------------------------------
// A VoiceProfile captures a user's unique writing style on LinkedIn so that
// AI-generated content can match their authentic voice.
// ---------------------------------------------------------------------------

// ---- Enums / union types ---------------------------------------------------

/** Overall tone of the user's writing. */
export type Tone =
  | 'professional'
  | 'conversational'
  | 'inspirational'
  | 'educational'
  | 'humorous'
  | 'provocative'
  | 'storytelling'
  | 'authoritative';

/** Common hook/opening patterns the user favors. */
export type HookPattern =
  | 'question'
  | 'bold_statement'
  | 'statistic'
  | 'story'
  | 'contrarian'
  | 'listicle'
  | 'quote'
  | 'personal_anecdote'
  | 'problem_statement';

/** Common call-to-action patterns the user favors. */
export type CTAPattern =
  | 'question'
  | 'agree_disagree'
  | 'share_experience'
  | 'tag_someone'
  | 'follow_for_more'
  | 'link_in_comments'
  | 'dm_me'
  | 'repost'
  | 'none';

/** How frequently the user employs emojis. */
export type EmojiFrequency = 'none' | 'minimal' | 'moderate' | 'heavy';

/** Preferred hashtag strategy. */
export type HashtagStyle =
  | 'none'
  | 'minimal'       // 1-2
  | 'moderate'       // 3-5
  | 'heavy'          // 6+
  | 'branded_only';  // only custom/branded tags

/** Overall formatting approach. */
export type FormattingStyle =
  | 'dense'          // long paragraphs
  | 'scannable'      // short paragraphs, bullet points
  | 'one_liner'      // one sentence per line
  | 'mixed';

/** Line-break cadence preference. */
export type LineBreakStyle =
  | 'none'           // no extra breaks
  | 'every_sentence' // break after each sentence
  | 'every_few'      // break every 2-3 sentences
  | 'paragraph';     // standard paragraph breaks

// ---- Confidence-scored trait ------------------------------------------------

/**
 * A trait value paired with a confidence score (0-1).
 * Confidence is derived from how much source material supports the trait.
 */
export interface ScoredTrait<T> {
  readonly value: T;
  readonly confidence: number; // 0..1
}

// ---- Sub-objects ------------------------------------------------------------

/** Vocabulary and phrasing characteristics. */
export interface VocabularyProfile {
  /** Words / phrases the user uses often. */
  readonly frequentWords: readonly string[];
  /** Words / phrases the user never uses. */
  readonly avoidedWords: readonly string[];
  /** Industry jargon the user is comfortable with. */
  readonly jargonTerms: readonly string[];
  /** Average reading level (Flesch-Kincaid grade). */
  readonly readingLevel: number | null;
  /** Typical sentence length in words. */
  readonly avgSentenceLength: number | null;
}

/** Emoji usage profile. */
export interface EmojiProfile {
  readonly frequency: EmojiFrequency;
  /** Specific emojis the user favors (e.g. ["🚀", "💡"]). */
  readonly preferred: readonly string[];
  /** Whether emojis are used as bullet markers. */
  readonly usedAsBullets: boolean;
}

/** Hashtag usage profile. */
export interface HashtagProfile {
  readonly style: HashtagStyle;
  /** Hashtags the user consistently includes. */
  readonly recurring: readonly string[];
  /** Where hashtags are placed in the post. */
  readonly placement: 'inline' | 'end' | 'first_comment';
}

/** Formatting and structural preferences. */
export interface FormattingProfile {
  readonly style: FormattingStyle;
  readonly lineBreaks: LineBreakStyle;
  /** Whether the user uses bullet points or numbered lists. */
  readonly usesLists: boolean;
  /** Typical post length in characters. */
  readonly avgPostLength: number | null;
  /** Whether the user separates the hook from the body visually. */
  readonly separatesHook: boolean;
}

// ---- Main entity ------------------------------------------------------------

/**
 * Complete voice profile for a user.
 * Generated by analyzing their existing LinkedIn posts.
 */
export interface VoiceProfile {
  readonly id: string;
  readonly userId: string;

  // Core style traits (with confidence)
  readonly tone: ScoredTrait<Tone>;
  readonly hookPatterns: readonly ScoredTrait<HookPattern>[];
  readonly ctaPatterns: readonly ScoredTrait<CTAPattern>[];

  // Detailed profiles
  readonly vocabulary: VocabularyProfile;
  readonly emoji: EmojiProfile;
  readonly hashtags: HashtagProfile;
  readonly formatting: FormattingProfile;

  // Metadata
  /** Number of posts analyzed to build this profile. */
  readonly postsAnalyzed: number;
  /** Overall confidence in the profile (0-1). */
  readonly overallConfidence: number;
  readonly createdAt: string;
  readonly updatedAt: string;
}

